func TestDecodeNetwork_SystemdNotifySocket(t *testing.T) {
	h, rest := decodeFullRecord(t, networkUnixBytes)
	if h.Type != StreamNetwork || h.Group != GroupNetwork {
		t.Fatalf("header = %+v", h)
	}
	n, err := DecodeNetwork(rest)
	if err != nil {
		t.Fatal(err)
	}
	if n.ObjectID != 1 || n.FD != 18 {
		t.Fatalf("ObjectID/FD = %d/%d", n.ObjectID, n.FD)
	}
	if n.Local.Type != SocketEndpointUnix || string(n.Local.Address) != "/run/systemd/notify\x00" {
		t.Fatalf("Local = %+v", n.Local)
	}
	if n.Peer.Type != SocketEndpointNone {
		t.Fatalf("Peer.Type = %d, want none (unconnected datagram socket)", n.Peer.Type)
	}
}
