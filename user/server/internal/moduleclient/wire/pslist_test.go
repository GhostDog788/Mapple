func TestDecodeSecurity_Root(t *testing.T) {
	h, rest := decodeFullRecord(t, securityObj1Bytes)
	if h.Type != StreamSecurity || h.Group != GroupSecurity {
		t.Fatalf("header = %+v", h)
	}
	sec, err := DecodeSecurity(rest)
	if err != nil {
		t.Fatal(err)
	}
	if sec.ObjectID != 1 || sec.UID != 0 || sec.GID != 0 || sec.EffectiveUID != 0 {
		t.Fatalf("DecodeSecurity() core identity = %+v", sec)
	}
	if sec.LSMProvider != "apparmor" {
		t.Fatalf("LSMProvider = %q, want apparmor", sec.LSMProvider)
	}
	if len(sec.SupplementaryGroups) != 0 {
		t.Fatalf("SupplementaryGroups = %v, want empty (root has none here)", sec.SupplementaryGroups)
	}
	if sec.CapabilityEffective != 0x1ffffffffff {
		t.Fatalf("CapabilityEffective = %#x, want full root capability set", sec.CapabilityEffective)
	}
}

func TestDecodeIdentity_Systemd(t *testing.T) {
	h, rest := decodeFullRecord(t, identityObj1Bytes)
	if h.Type != StreamIdentity || h.Group != GroupIdentity {
		t.Fatalf("header = %+v", h)
	}
	id, err := DecodeIdentity(rest)
	if err != nil {
		t.Fatal(err)
	}
	if id.ObjectID != 1 {
		t.Fatalf("ObjectID = %d, want 1", id.ObjectID)
	}
	if id.CommandLineStatus != CommandLineAvailable || id.CommandLine != "/sbin/init\x00nokaslr\x00" {
		t.Fatalf("CommandLine = %q (status %d)", id.CommandLine, id.CommandLineStatus)
	}
	if id.ExecutableStatus != ExecutableAvailable || id.ExecutablePath != "/usr/lib/systemd/systemd" {
		t.Fatalf("ExecutablePath = %q (status %d)", id.ExecutablePath, id.ExecutableStatus)
	}
	if id.ExecutableSize != 100816 {
		t.Fatalf("ExecutableSize = %d, want 100816", id.ExecutableSize)
	}
}

