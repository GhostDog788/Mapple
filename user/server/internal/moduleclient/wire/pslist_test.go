func decodeFullRecord(t *testing.T, buf []byte) (RecordHeader, []byte) {
	t.Helper()
	h, rest, err := DecodeRecordHeader(buf)
	if err != nil {
		t.Fatalf("DecodeRecordHeader() error = %v", err)
	}
	return h, rest
}

func TestDecodeSnapshotBegin(t *testing.T) {
	h, rest := decodeFullRecord(t, snapshotBeginBytes)
	if h.Type != StreamSnapshotBegin || h.Group != 0 {
		t.Fatalf("header = %+v", h)
	}
	b, err := DecodeSnapshotBegin(rest)
	if err != nil {
		t.Fatal(err)
	}
	want := SnapshotBegin{RequestedGroups: 0xe5, EffectiveGroups: 0xe5, SupportedGroups: 0xe5, StartBoottimeNS: 0x0439af0a895e}
	if b != want {
		t.Fatalf("DecodeSnapshotBegin() = %+v, want %+v", b, want)
	}
}

func TestDecodeSnapshotEnd(t *testing.T) {
	h, rest := decodeFullRecord(t, snapshotEndBytes)
	if h.Type != StreamSnapshotEnd {
		t.Fatalf("header = %+v", h)
	}
	e, err := DecodeSnapshotEnd(rest)
	if err != nil {
		t.Fatal(err)
	}
	want := SnapshotEnd{Status: SnapshotComplete, TaskCount: 108, ObjectCount: 161, EndBoottimeNS: 0x0439af58ef77}
	if e != want {
		t.Fatalf("DecodeSnapshotEnd() = %+v, want %+v", e, want)
	}
}

